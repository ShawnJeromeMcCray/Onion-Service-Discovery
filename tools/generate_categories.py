"""Generate draft category types/localization from the sole registry artifact."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]


def generate() -> None:
    registry = json.loads((ROOT / 'protocol/registries/categories-v1.json').read_text())
    entries = registry['categories']
    ids = sorted(entry['id'] for entry in entries)
    if registry['registry_version'] != 1 or len(ids) != len(set(ids)) or 'adult' not in ids:
        raise ValueError('CATEGORY_REGISTRY_INVALID')
    if any(re.fullmatch(r'[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?', value) is None for value in ids):
        raise ValueError('CATEGORY_REGISTRY_INVALID')
    header = '// Generated by tools/generate_categories.py; draft, not Protocol Freeze.\n'
    php = '<?php\ndeclare(strict_types=1);\nnamespace OnionServiceDiscovery\\Domain;\n'
    php += header + 'enum CategoryId: string\n{\n'
    php += ''.join(f"    case {value.upper()} = '{value}';\n" for value in ids)
    php += '}\n'
    (ROOT / 'node-php/src/Domain/CategoryId.php').write_text(php)
    ts = header + 'export const CATEGORY_IDS = ' + json.dumps(ids) + ' as const;\n'
    ts += 'export type CategoryId = typeof CATEGORY_IDS[number];\n'
    ts += 'export const CATEGORY_LABELS: Readonly<Record<CategoryId, string>> = Object.freeze('
    ts += json.dumps({entry['id']: entry['canonical_label'] for entry in entries}, sort_keys=True) + ');\n'
    (ROOT / 'web-local-search-client/src/protocol/category-id.ts').write_text(ts)
    (ROOT / 'validator-python/category_ids.py').write_text(
        '# Generated by tools/generate_categories.py; draft registry.\nCATEGORY_IDS = frozenset('
        + repr(ids) + ')\n')
    locales = ROOT / 'protocol/registries/localization'
    locales.mkdir(exist_ok=True)
    (locales / 'categories-en.json').write_text(json.dumps({entry['id']: entry['canonical_label'] for entry in entries}, indent=2, sort_keys=True) + '\n')


if __name__ == '__main__':
    generate()
